import test from 'node:test';
import assert from 'node:assert/strict';
import { archiveLocation, initializeMemory, prepareMemoryPrompt, filterArchivedPrompt } from '../功能/场景记忆运行.ts';

test('切换地点时总结，失败保留原文，下次切换重试，聊天隔离', async () => {
  const states = { a: {}, b: {} };
  let active = 'a';
  let fail = true;
  const chat = [{ message_id: 0, role: 'assistant', message: '[旁白]\n场景开始' }];
  let injected;
  globalThis.SillyTavern = { getCurrentChatId: () => active };
  globalThis.getLastMessageId = () => chat.length - 1;
  globalThis.getChatMessages = () => chat;
  globalThis.getVariables = () => states[active];
  globalThis.updateVariablesWith = fn => { states[active] = fn(states[active]); return states[active]; };
  globalThis.generateRaw = async () => { if (fail) throw Error('离线'); return JSON.stringify({ 玩家: '认识爱丽丝', 爱丽丝: '认识玩家' }); };
  globalThis.toastr = { warning() {} };
  globalThis.uninjectPrompts = () => {};
  globalThis.injectPrompts = prompts => { injected = prompts; };
  initializeMemory();
  chat.push({ message_id: 1, role: 'user', message: '你好' });
  const loading = [];
  await archiveLocation('酒馆', ['爱丽丝'], 'a', active => loading.push(active));
  assert.deepEqual(loading, [true, false]);
  assert.equal(states.a.rpgSceneMemories.scenes[0].knowledge, undefined);
  const first = [{ role: 'user', content: '你好' }];
  filterArchivedPrompt(first);
  assert.equal(first.length, 1);
  chat.push({ message_id: 2, role: 'assistant', message: '[旁白]\n学院' });
  fail = false;
  loading.length = 0;
  await archiveLocation('学院', ['蕾拉妮'], 'a', active => loading.push(active));
  assert.deepEqual(loading, [true, false]);
  assert.equal(states.a.rpgSceneMemories.scenes[0].knowledge.爱丽丝, '认识玩家');
  prepareMemoryPrompt({ player: { area: { place: '酒馆' } }, locations: { 酒馆: { present: ['爱丽丝'] } } });
  assert.match(injected[0].content, /认识玩家/);
  const prompt = [{ role: 'user', content: '你好' }, { role: 'user', content: '当前消息' }];
  filterArchivedPrompt(prompt);
  assert.deepEqual(prompt, [{ role: 'user', content: '当前消息' }]);
  active = 'b';
  initializeMemory();
  assert.deepEqual(states.b.rpgSceneMemories.scenes, []);
});
